#define OUI_N (sizeof(OUI)/sizeof(Oui))

const char *oui_vendor(const uint8_t mac[6]) {
    for (size_t i = 0; i < OUI_N; i++) {
        if (mac[0] == OUI[i].o[0] && mac[1] == OUI[i].o[1] && mac[2] == OUI[i].o[2]) return OUI[i].v;
    }
    return "unknown";
}

int resolve_name(uint32_t ip, char *out, size_t len) {
    /* Reverse DNS is not performed by default to avoid blocking the discovery job.
     * The web UI already shows the IP + vendor; mDNS/NetBIOS enrichment is a later step. */
    (void)ip;
    if (out && len) out[0] = 0;
    return -1;
}
